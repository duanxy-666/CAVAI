def main():
    root = Path(__file__).resolve().parent
    if not ((root / "run.py").is_file() and (root / "cavai" / "app.py").is_file()):
        raise SystemExit("请把 upgrade_cavai.py 放在 CAVAI_v0.1 根目录（run.py 同级）再运行。")

    backup_root = root / ".cavai_backup_before_v02"
    files = base64.b85decode(_PACKAGE)
    with ZipFile(io.BytesIO(zlib.decompress(files))) as archive:
        names = archive.namelist()
        for name in names:
            rel = Path(name)
            if rel.is_absolute() or ".." in rel.parts:
                raise SystemExit("更新包路径不安全，已停止。")
        for name in names:
            destination = root / name
            destination.parent.mkdir(parents=True, exist_ok=True)
            if destination.is_file():
                backup = backup_root / name
                if not backup.exists():
                    backup.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(destination, backup)
            destination.write_bytes(archive.read(name))
    print("CAVAI v0.2 原首页 CATPart 集成完成。")
    print("被替换的旧文件备份在：", backup_root)
    print("下一步：先启动 CATIA V5，再运行 python run.py")
    print("浏览器打开原地址 http://127.0.0.1:8000 并按 Ctrl+F5 强制刷新。")


if __name__ == "__main__":
    main()
